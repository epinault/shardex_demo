# Postgres port. Defaults to 5432; override with SHARDEX_DEMO_PGPORT so the demo
# can coexist with an existing Postgres (the docker-compose file honors it too).
pg_port = String.to_integer(System.get_env("SHARDEX_DEMO_PGPORT") || "5432")

# The catalog database (tenant directory).
config :shardex_demo, ShardexDemo.CatalogRepo,
  username: "postgres",
  password: "postgres",
  hostname: "localhost",
  port: pg_port,
  database: "shardex_demo_catalog_dev",
  stacktrace: true,
  show_sensitive_data_on_connection_error: true,
  pool_size: 10

# Base config for the shard repo. Note there is NO `:database` here — shardex
# merges a per-shard `database:` over this for each pool.
config :shardex_demo, ShardexDemo.ShardRepo,
  username: "postgres",
  password: "postgres",
  hostname: "localhost",
  port: pg_port,
  stacktrace: true,
  show_sensitive_data_on_connection_error: true,
  pool_size: 5

# The shardex instance: two shard databases, routed by a database-backed
# directory strategy (ShardexDemo.OrgDirectory) with a short cache in front.
config :shardex_demo, ShardexDemo.Shards,
  strategy: {Shardex.Strategy.Cached, inner: ShardexDemo.OrgDirectory, ttl: :timer.minutes(10)},
  shards: [
    shard_1:
      {Shardex.Adapter.Ecto,
       repo: ShardexDemo.ShardRepo, config: [database: "shardex_demo_shard_1_dev"]},
    shard_2:
      {Shardex.Adapter.Ecto,
       repo: ShardexDemo.ShardRepo, config: [database: "shardex_demo_shard_2_dev"]}
  ]

